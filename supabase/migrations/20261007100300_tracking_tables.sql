  as permissive for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

create policy weekly_scores_admin_all on public.weekly_scores
  as permissive for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

create policy action_items_admin_all on public.action_items
  as permissive for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

create policy replacements_admin_all on public.replacements
  as permissive for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

create policy weekly_reports_admin_all on public.weekly_reports
  as permissive for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

revoke all on table
  public.staff, public.weekly_scores, public.action_items, public.replacements, public.weekly_reports
  from anon;
revoke truncate, references, trigger on table
  public.staff, public.weekly_scores, public.action_items, public.replacements, public.weekly_reports
  from authenticated;
